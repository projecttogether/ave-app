import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { FORMULA_POLICY } from '../src/lib/indicators/policy'
import { INDICATOR_CONFIG } from '../src/lib/indicators/config'

const snake = (value: string) => value.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`)
const column = (key: string) => `d.${snake(key)}`
const measurements = Object.entries(INDICATOR_CONFIG).filter(([key]) =>
    ['total_spend', 'plant_based_percentage', 'organic_percentage', 'fair_trade_percentage', 'food_waste'].includes(key)
).map(([key, config]) => {
    const fields = config.spendColumns ?? (config.spendColumn ? [config.spendColumn] : [config.column!])
    const sum = (cols: string[]) => cols.map(c => `coalesce(${column(c)}, 0) * ${config.weights?.[c as keyof typeof config.weights] ?? 1}`).join(' + ')
    const numerator = config.calculation === 'inverse_sum' ? `greatest(0, coalesce(d.total_food_spend, 0) - (${sum(fields)}))` : sum(fields)
    const denominator = config.computed ? sum(config.denominatorColumns ?? ['totalFoodSpend']) : 'NULL::numeric'
    return `      ('${key}', ${numerator}, ${denominator}, ${fields.map(c => `${column(c)} IS NOT NULL`).join(' OR ')})`
}).join(',\n')

// Selection and scope stay in the reviewed SQL template. Fields, weights,
// scoring options and maxima are generated from the same policy as TypeScript.
let output = readFileSync('src/lib/indicators/formula-template.sql', 'utf8')
output = output.replace(/(?<=CROSS JOIN LATERAL \(VALUES\n)[\s\S]*?(?=\n    \) AS v)/, measurements)
const questions = FORMULA_POLICY.questions.map(q => ({ question_key: q.key, indicator_slug: q.indicator, max_points: q.maxPoints, points: q.points }))
output = output.replace(/\$policy\$[\s\S]*?\$policy\$/, `$policy$${JSON.stringify(questions, null, 2)}$policy$`)
output = output.replace('max_points int)', 'max_points int, points jsonb)')
output = output.replace(/sum\(CASE WHEN q.max_points = 2 THEN[\s\S]*?END END\) AS points/, 'sum((q.points ->> r.response_option)::numeric) AS points')
output = output.replace("WHERE nullif(r.response_option, '') IS NOT NULL", "WHERE q.points ? r.response_option")
const hash = createHash('sha256').update(JSON.stringify(FORMULA_POLICY)).digest('hex')
output = `-- Generated by npm run formulas:generate. Do not edit.\n${output}\nCREATE OR REPLACE FUNCTION indicator_formula_revision() RETURNS text\nLANGUAGE sql IMMUTABLE AS $$ SELECT '${FORMULA_POLICY.version}:${hash}'::text $$;\n`
const path = 'drizzle/0034_generated_indicator_formulas.sql'
if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output) throw new Error('Generated SQL is stale. Run npm run formulas:generate and review the policy change.')
} else writeFileSync(path, output)
